import { createHmac, createHash, randomUUID } from "node:crypto";
import { createReadStream, createWriteStream, mkdirSync, unlinkSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { env } from "../env.ts";
import { AppError } from "./errors.ts";

export type StorageBackend = "local" | "s3";

export interface ObjectStore {
  readonly name: StorageBackend;
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Readable>;
  delete(key: string): Promise<void>;
}

const localRoot = env.UPLOAD_DIR ? env.UPLOAD_DIR : join(process.cwd(), "uploads");

export class LocalObjectStore implements ObjectStore {
  readonly name = "local" as const;
  private readonly root: string;

  constructor(root = localRoot) {
    this.root = root;
    mkdirSync(this.root, { recursive: true });
  }

  private pathFor(key: string) {
    // Keys are always generated by us (verification/<uuid>.ext) — block path traversal.
    if (key.includes("..") || key.startsWith("/") || key.includes("\\")) {
      throw new AppError(400, "bad_request", "Invalid storage key");
    }
    return join(this.root, key);
  }

  async put(key: string, data: Buffer, _contentType: string) {
    const full = this.pathFor(key);
    mkdirSync(dirname(full), { recursive: true });
    await pipeline(Readable.from(data), createWriteStream(full));
  }

  private resolve(key: string) {
    const full = this.pathFor(key);
    if (existsSync(full)) return full;
    // Pre-011 uploads stored only the basename under uploads/verification/.
    if (!key.includes("/") && !key.includes("\\")) {
      const legacy = join(this.root, "verification", key);
      if (existsSync(legacy)) return legacy;
    }
    return null;
  }

  async get(key: string) {
    const full = this.resolve(key);
    if (!full) throw new AppError(404, "not_found", "File not found");
    return createReadStream(full);
  }

  async delete(key: string) {
    const full = this.resolve(key);
    if (!full) return;
    try {
      unlinkSync(full);
    } catch {
      /* ignore missing */
    }
  }
}

/** S3-compatible object store (AWS S3, Cloudflare R2, MinIO) via SigV4 + fetch. */
export class S3ObjectStore implements ObjectStore {
  readonly name = "s3" as const;

  constructor(
    private readonly bucket: string,
    private readonly region: string,
    private readonly accessKeyId: string,
    private readonly secretAccessKey: string,
    private readonly endpoint?: string,
  ) {}

  private hostPath(key: string) {
    const encodedKey = key
      .split("/")
      .map((p) => encodeURIComponent(p).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`))
      .join("/");
    if (this.endpoint) {
      const base = this.endpoint.replace(/\/$/, "");
      const url = new URL(base);
      return {
        url: `${base}/${this.bucket}/${encodedKey}`,
        host: url.host,
        canonicalUri: `/${this.bucket}/${encodedKey}`,
      };
    }
    const host = `${this.bucket}.s3.${this.region}.amazonaws.com`;
    return { url: `https://${host}/${encodedKey}`, host, canonicalUri: `/${encodedKey}` };
  }

  private async signedFetch(method: string, key: string, body?: Buffer, contentType?: string) {
    const { url, host, canonicalUri } = this.hostPath(key);
    const now = new Date();
    const amzDate = now.toISOString().replace(/[:-]|\.\d{3}/g, "");
    const dateStamp = amzDate.slice(0, 8);
    const payloadHash = createHash("sha256").update(body ?? "").digest("hex");
    const headers: Record<string, string> = {
      host,
      "x-amz-content-sha256": payloadHash,
      "x-amz-date": amzDate,
    };
    if (contentType) headers["content-type"] = contentType;
    if (body) headers["content-length"] = String(body.length);

    const signedHeaderKeys = Object.keys(headers).sort();
    const signedHeaders = signedHeaderKeys.join(";");
    const canonicalHeaders = signedHeaderKeys.map((k) => `${k}:${headers[k]}\n`).join("");
    const canonicalRequest = [
      method,
      canonicalUri,
      "",
      canonicalHeaders,
      signedHeaders,
      payloadHash,
    ].join("\n");

    const credentialScope = `${dateStamp}/${this.region}/s3/aws4_request`;
    const stringToSign = [
      "AWS4-HMAC-SHA256",
      amzDate,
      credentialScope,
      createHash("sha256").update(canonicalRequest).digest("hex"),
    ].join("\n");

    const kDate = createHmac("sha256", `AWS4${this.secretAccessKey}`).update(dateStamp).digest();
    const kRegion = createHmac("sha256", kDate).update(this.region).digest();
    const kService = createHmac("sha256", kRegion).update("s3").digest();
    const kSigning = createHmac("sha256", kService).update("aws4_request").digest();
    const signature = createHmac("sha256", kSigning).update(stringToSign).digest("hex");

    headers.authorization = [
      `AWS4-HMAC-SHA256 Credential=${this.accessKeyId}/${credentialScope}`,
      `SignedHeaders=${signedHeaders}`,
      `Signature=${signature}`,
    ].join(", ");

    const res = await fetch(url, { method, headers, body: body ? new Uint8Array(body) : undefined });
    return res;
  }

  async put(key: string, data: Buffer, contentType: string) {
    const res = await this.signedFetch("PUT", key, data, contentType);
    if (!res.ok) {
      console.error(`[storage:s3] PUT ${key} ${res.status} ${await res.text()}`);
      throw new AppError(502, "storage_failed", "Could not store the file. Try again.");
    }
  }

  async get(key: string) {
    const res = await this.signedFetch("GET", key);
    if (res.status === 404) throw new AppError(404, "not_found", "File not found");
    if (!res.ok || !res.body) {
      console.error(`[storage:s3] GET ${key} ${res.status}`);
      throw new AppError(502, "storage_failed", "Could not read the file.");
    }
    return Readable.fromWeb(res.body as import("node:stream/web").ReadableStream);
  }

  async delete(key: string) {
    const res = await this.signedFetch("DELETE", key);
    if (!res.ok && res.status !== 404) {
      console.error(`[storage:s3] DELETE ${key} ${res.status} ${await res.text()}`);
    }
  }
}

export function createObjectStore(): ObjectStore {
  if (env.STORAGE_BACKEND === "s3") {
    return new S3ObjectStore(
      env.S3_BUCKET!,
      env.S3_REGION!,
      env.S3_ACCESS_KEY_ID!,
      env.S3_SECRET_ACCESS_KEY!,
      env.S3_ENDPOINT,
    );
  }
  return new LocalObjectStore();
}

export const objectStore = createObjectStore();

export function newVerificationObjectKey(mimeType: string) {
  const ext =
    mimeType === "application/pdf"
      ? "pdf"
      : mimeType === "image/png"
        ? "png"
        : mimeType === "image/webp"
          ? "webp"
          : "jpg";
  return `verification/${randomUUID()}.${ext}`;
}

/** Best-effort delete used when a DB insert fails after put. */
export async function safeDeleteObject(key: string) {
  try {
    await objectStore.delete(key);
  } catch {
    /* ignore */
  }
}
